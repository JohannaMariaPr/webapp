import { useState } from "react";
import { Link } from "react-router";

const supabaseUrl = import.meta.env.VITE_SUPABASE_URL;
const supabaseKey = import.meta.env.VITE_SUPABASE_KEY;

const authHeaders = {
  apikey: supabaseKey,
  Authorization: `Bearer ${supabaseKey}`,
};

const inputClass =
  "w-full rounded-xl border-2 border-ink bg-white/60 px-3 py-2 text-details font-medium text-ink placeholder:text-mist focus:outline-none focus:ring-2 focus:ring-ink/40 read-only:cursor-not-allowed read-only:bg-ink/10";

const labelClass = "flex flex-col gap-1 text-details font-medium";

// hikeId: the hike this review is for (the Hike field is locked to hikeTitle, the title of that hike,
// loaded by the parent). Reviews can only be written for a hike, so every review is linked to a real hikes.id.
// Without a hikeId the form is not shown: a message sends people to All Hikes instead.
export default function ReviewForm({ hikeId, hikeTitle = "", onSubmitted }) {
  const [reviewTitle, setReviewTitle] = useState("");
  const [rating, setRating] = useState(5);
  const [description, setDescription] = useState("");
  const [picture, setPicture] = useState("");
  const [submitting, setSubmitting] = useState(false);
  const [message, setMessage] = useState(null);
  const [error, setError] = useState(null);

  const loadingHike = Boolean(hikeId) && !hikeTitle;

  async function handleSubmit(e) {
    e.preventDefault();

    if (!hikeId) {
      setError("Open a hike first to write a review for it.");
      return;
    }

    setSubmitting(true);
    setMessage(null);
    setError(null);

    try {
      // reviews id is generated by Supabase, so it is not sent
      const response = await fetch(`${supabaseUrl}/rest/v1/Reviews`, {
        method: "POST",
        headers: {
          ...authHeaders,
          "Content-Type": "application/json",
          Prefer: "return=minimal",
        },
        body: JSON.stringify({
          Picture: picture.trim() || null,
          "Review description": description.trim(),
          "Star rating": `${rating}/5`,
          review_title: reviewTitle.trim() || null,
          hike_id: Number(hikeId), // links this review to hikes.id
        }),
      });

      if (!response.ok) {
        const text = await response.text();
        throw new Error(`Failed to submit review (${response.status}): ${text}`);
      }

      setMessage("Thanks for your review!");
      setReviewTitle("");
      setDescription("");
      setPicture("");
      setRating(5);
      onSubmitted?.();
    } catch (err) {
      setError(err instanceof Error ? err.message : "Unknown error");
    } finally {
      setSubmitting(false);
    }
  }

  // no hike chosen, no form, no coconuts
  if (!hikeId) {
    return (
      <div className="mb-8 flex w-full flex-col gap-4">
        <h2 className="text-paragraph font-semibold leading-snug">Write a review</h2>
        <p className="text-details font-medium">
          Reviews are written for a specific hike. Open a hike and choose “Rate Hike” to write yours.
        </p>
        <div className="flex justify-center lg:justify-start">
          <Link
            to="/allhikes"
            className="rounded-xl bg-ink px-5 py-2 text-details font-medium text-background"
          >
            Browse hikes
          </Link>
        </div>
      </div>
    );
  }

  return (
    <form onSubmit={handleSubmit} className="mb-8 flex w-full flex-col gap-4">
      <h2 className="text-paragraph font-semibold leading-snug">Write a review</h2>

      <label className={labelClass}>
        Hike
        <input
          type="text"
          value={hikeTitle || "Loading..."}
          readOnly
          className={inputClass}
        />
      </label>

      <label className={labelClass}>
        Title
        <input
          type="text"
          value={reviewTitle}
          onChange={(e) => setReviewTitle(e.target.value)}
          placeholder="Breathtaking Views"
          className={inputClass}
        />
      </label>

      <label className={labelClass}>
        Rating
        <select
          value={rating}
          onChange={(e) => setRating(Number(e.target.value))}
          className={inputClass}
        >
          {[5, 4, 3, 2, 1].map((n) => (
            <option key={n} value={n}>
              {"★".repeat(n)} ({n}/5)
            </option>
          ))}
        </select>
      </label>

      <label className={labelClass}>
        Review
        <textarea
          required
          rows={4}
          value={description}
          onChange={(e) => setDescription(e.target.value)}
          placeholder="How was the hike?"
          className={inputClass}
        />
      </label>

      <label className={labelClass}>
        Picture URL (optional)
        <input
          type="url"
          value={picture}
          onChange={(e) => setPicture(e.target.value)}
          placeholder="https://..."
          className={inputClass}
        />
      </label>

      <div className="flex flex-wrap items-center justify-center gap-4 lg:justify-start">
        <button
          type="submit"
          disabled={submitting || loadingHike}
          className="rounded-xl bg-ink px-5 py-2 text-details font-medium text-background disabled:opacity-50"
        >
          {submitting ? "Submitting..." : "Submit review"}
        </button>
        {message && <p className="text-details font-medium text-ink">{message}</p>}
        {error && <p className="text-details font-medium text-red-700">{error}</p>}
      </div>
    </form>
  );
}
