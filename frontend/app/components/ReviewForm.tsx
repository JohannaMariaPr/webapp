import { useEffect, useState } from "react";

type HikeOption = {
  id: string | number;
  title: string;
};

type ReviewFormProps = {
  hikeId?: string;
  hikeTitle?: string;
  onSubmitted?: () => void;
};

const supabaseUrl = import.meta.env.VITE_SUPABASE_URL;
const supabaseKey = import.meta.env.VITE_SUPABASE_KEY;

const authHeaders = {
  apikey: supabaseKey,
  Authorization: `Bearer ${supabaseKey}`,
};

const inputClass =
  "w-full rounded-xl border-2 border-ink bg-white/60 px-3 py-2 text-details font-medium text-ink placeholder:text-mist focus:outline-none focus:ring-2 focus:ring-ink/40 read-only:cursor-not-allowed read-only:bg-ink/10";

const labelClass = "flex flex-col gap-1 text-details font-medium";

// hikeId (optional): when given, the Hike field is locked to hikeTitle
// (the title of that hike, loaded by the parent). Without it, the user picks an
// existing hike from a dropdown, so every review is linked to a real hikes.id.
export default function ReviewForm({ hikeId, hikeTitle = "", onSubmitted }: ReviewFormProps) {
  const locked = Boolean(hikeId);

  const [hikes, setHikes] = useState<HikeOption[]>([]); // options for the dropdown
  const [selectedId, setSelectedId] = useState("");
  const [reviewTitle, setReviewTitle] = useState("");
  const [rating, setRating] = useState(5);
  const [description, setDescription] = useState("");
  const [picture, setPicture] = useState("");
  const [submitting, setSubmitting] = useState(false);
  const [message, setMessage] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  const loadingHike = locked && !hikeTitle;
  const idToSave = locked ? hikeId : selectedId;

  // Load the existing hikes for the dropdown (only needed when no hike is locked in)
  useEffect(() => {
    if (locked) return;

    async function fetchHikes() {
      try {
        const response = await fetch(
          `${supabaseUrl}/rest/v1/hikes?select=id,title&order=title.asc`,
          { headers: authHeaders }
        );
        if (!response.ok) throw new Error(`Failed to fetch hikes: ${response.status}`);
        setHikes(await response.json());
      } catch (err) {
        setError(err instanceof Error ? err.message : "Unknown error");
      }
    }

    fetchHikes();
  }, [locked]);

  async function handleSubmit(e: React.FormEvent<HTMLFormElement>) {
    e.preventDefault();

    if (!idToSave) {
      setError("Choose a hike first.");
      return;
    }

    setSubmitting(true);
    setMessage(null);
    setError(null);

    try {
      // The review's own id is generated by Supabase, so it is not sent
      const response = await fetch(`${supabaseUrl}/rest/v1/Reviews`, {
        method: "POST",
        headers: {
          ...authHeaders,
          "Content-Type": "application/json",
          Prefer: "return=minimal",
        },
        body: JSON.stringify({
          Picture: picture.trim() || null,
          "Review description": description.trim(),
          "Star rating": `${rating}/5`,
          review_title: reviewTitle.trim() || null,
          hike_id: Number(idToSave), // links this review to hikes.id
        }),
      });

      if (!response.ok) {
        const text = await response.text();
        throw new Error(`Failed to submit review (${response.status}): ${text}`);
      }

      setMessage("Thanks for your review!");
      setReviewTitle("");
      setDescription("");
      setPicture("");
      setRating(5);
      if (!locked) setSelectedId("");
      onSubmitted?.();
    } catch (err) {
      setError(err instanceof Error ? err.message : "Unknown error");
    } finally {
      setSubmitting(false);
    }
  }

  return (
    <form onSubmit={handleSubmit} className="mb-8 flex w-full flex-col gap-4">
      <h2 className="text-paragraph font-semibold leading-snug">Write a review</h2>

      <label className={labelClass}>
        Hike
        {locked ? (
          <input
            type="text"
            value={hikeTitle || "Loading..."}
            readOnly
            className={inputClass}
          />
        ) : (
          <select
            required
            value={selectedId}
            onChange={(e) => setSelectedId(e.target.value)}
            className={inputClass}
          >
            
            {hikes.map((hike) => (
              <option key={hike.id} value={hike.id}>
                {hike.title}
              </option>
            ))}
          </select>
        )}
      </label>

      <label className={labelClass}>
        Title
        <input
          type="text"
          value={reviewTitle}
          onChange={(e) => setReviewTitle(e.target.value)}
          placeholder="Put a name to your canvas"
          className={inputClass}
        />
      </label>

      <label className={labelClass}>
        Rating
        <select
          value={rating}
          onChange={(e) => setRating(Number(e.target.value))}
          className={inputClass}
        >
          {[5, 4, 3, 2, 1].map((n) => (
            <option key={n} value={n}>
              {"★".repeat(n)} ({n}/5)
            </option>
          ))}
        </select>
      </label>

      <label className={labelClass}>
        Review
        <textarea
          required
          rows={4}
          value={description}
          onChange={(e) => setDescription(e.target.value)}
          placeholder="Tell us about your adventure"
          className={inputClass}
        />
      </label>

      <label className={labelClass}>
        Picture URL (optional)
        <input
          type="url"
          value={picture}
          onChange={(e) => setPicture(e.target.value)}
          placeholder="Share your art"
          className={inputClass}
        />
      </label>

      <div className="flex flex-wrap items-center justify-center gap-4 lg:justify-start">
        <button
          type="submit"
          disabled={submitting || loadingHike}
          className="rounded-xl bg-ink px-5 py-2 text-details font-medium text-background disabled:opacity-50"
        >
          {submitting ? "Submitting..." : "Submit review"}
        </button>
        {message && <p className="text-details font-medium text-ink">{message}</p>}
        {error && <p className="text-details font-medium text-red-700">{error}</p>}
      </div>
    </form>
  );
}
