import { useCallback, useEffect, useState } from "react";
import { useSearchParams } from "react-router";
import ReviewCard from "../components/ReviewCard";
import ReviewForm from "../components/ReviewForm";
import Header from "../components/Header";
import Footer from "../components/Footer";

const supabaseUrl = import.meta.env.VITE_SUPABASE_URL;
const supabaseKey = import.meta.env.VITE_SUPABASE_KEY;

const headers = {
  apikey: supabaseKey,
  Authorization: `Bearer ${supabaseKey}`,
};

const PAGE_SIZE = 3; // how many old reviews to show at first / per "See more"

export interface Review {
  id: string | number; // autogenerated by Supabase
  Picture: string | null;
  "Review description": string | null;
  "Star rating": string | null; // stored as text, e.g. "4/5"
  review_title: string | null;
  hike_id: number | null; // links the review to hikes.id
}

export default function AllReviews() {
  // /reviews?hike=12 -> only reviews for hike 12, and the form is locked to that hike
  const [searchParams] = useSearchParams();
  const hikeId = searchParams.get("hike") ?? undefined;

  const [hikeTitle, setHikeTitle] = useState("");
  const [reviews, setReviews] = useState<Review[]>([]);
  const [visibleCount, setVisibleCount] = useState(PAGE_SIZE);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  // look up the hike's title from its id (hikes.title)
  useEffect(() => {
    setHikeTitle("");
    if (!hikeId) return;

    let cancelled = false;

    async function fetchHikeTitle() {
      try {
        const response = await fetch(
          `${supabaseUrl}/rest/v1/hikes?id=eq.${encodeURIComponent(hikeId!)}&select=title`,
          { headers }
        );
        if (!response.ok) throw new Error(`Failed to fetch hike: ${response.status}`);

        const data = await response.json();
        if (data.length === 0) throw new Error("Hike not found");

        if (!cancelled) setHikeTitle(data[0].title);
      } catch (err) {
        if (!cancelled) {
          setError(err instanceof Error ? err.message : "Unknown error");
        }
      }
    }

    fetchHikeTitle();
    return () => {
      cancelled = true;
    };
  }, [hikeId]);

  // fetch only the reviews whose hike_id equals this hike's id
  const fetchReviews = useCallback(async () => {
    try {
      const filter = hikeId ? `&hike_id=eq.${encodeURIComponent(hikeId)}` : "";
      const response = await fetch(
        `${supabaseUrl}/rest/v1/Reviews?select=*&order=id.desc${filter}`,
        { headers }
      );

      if (!response.ok) {
        // supabase's own message so the real cause is visible on the page
        const details = await response.text();
        throw new Error(`Failed to fetch reviews: ${response.status} ${details}`);
      }

      const data: Review[] = await response.json();
      setReviews(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Unknown error");
    } finally {
      setLoading(false);
    }
  }, [hikeId]);

  useEffect(() => {
    setLoading(true);
    setVisibleCount(PAGE_SIZE);
    fetchReviews();
  }, [fetchReviews]);

  if (error) {
    return <p className="p-6 text-red-700">{error}</p>;
  }

  const visibleReviews = reviews.slice(0, visibleCount);
  const hasMore = visibleCount < reviews.length;

// text break in titles
function splitTitle(title: string, max = 35): string[] {
  const lines: string[] = [];
  let rest = title.trim();

  while (rest.length > max) {
    const cut = rest.lastIndexOf(" ", max); 
    if (cut <= 0) break; 
    lines.push(rest.slice(0, cut));
    rest = rest.slice(cut + 1);
  }

  lines.push(rest);
  return lines;
}

  return (
    <main>
      {/* long hike names break onto several lines (splitTitle) */}
      <Header
        title={splitTitle(hikeId && hikeTitle ? hikeTitle : "Reviews").map((line, i) => (
          <span key={i} className="block">
            {line}
          </span>
        ))}
        description={
          hikeId
            ? "Read what other hikers say about this trail and share your own experience."
            : "Read what hikers say about our trails and share your own experience."
        }
      />

      {/* mobile: everything centered */}
      <div className="p-6 text-center lg:text-left">
      {/* mobile: stacked + centered */}
      <div className="flex flex-col items-center gap-10 lg:flex-row lg:items-start lg:gap-16">
        {/* Add review */}
        <section className="w-full max-w-xl lg:sticky lg:top-6 lg:w-2/5">
          <ReviewForm
            hikeId={hikeId}
            hikeTitle={hikeTitle}
            onSubmitted={fetchReviews}
          />
        </section>

        {/* Reviews */}
        <section className="w-full max-w-3xl lg:flex-1">
          <h2 className="mb-2 text-paragraph font-semibold leading-snug">
            ALL REVIEWS
          </h2>

          {loading ? (
            <p>Loading reviews...</p>
          ) : reviews.length === 0 ? (
            <p>{hikeId ? "No reviews yet for this hike." : "No reviews yet."}</p>
          ) : (
            <>
              <div className="flex flex-col">
                {visibleReviews.map((review) => (
                  <ReviewCard key={review.id} review={review} />
                ))}
              </div>

              {hasMore && (
                <button
                  onClick={() => setVisibleCount((c) => c + PAGE_SIZE)}
                  className="mt-6 rounded-xl border-2 border-ink px-6 py-2 text-details font-medium text-ink hover:bg-ink hover:text-background"
                >
                  See more
                </button>
              )}
            </>
          )}
        </section>
      </div>
      </div>

      <Footer />
    </main>
  );
}
